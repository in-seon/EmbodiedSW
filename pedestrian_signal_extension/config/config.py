# ⚠️ 절대값은 아직 실측 전이다. 0.005는 기존 테스트 스크립트에서 쓰던 값일 뿐이다.
# config 위쪽 '축척과 모형 보행자 속도' 항목에 따르면 **2.5 cm/s(30cm를 12초)**여야
# 연장 초의 근거 자료를 그대로 쓸 수 있다. 스톱워치로 30cm 통과 시간을 재서 맞출 것.
MOTOR_STEP_DELAY_SEC = {
    2: 0.005,
    3: 0.005 * 1.25,
}

# START에 모드가 붙어 있지 않을 때 쓸 기본 속도 모드.
# 아두이노는 그냥 "START"만 보내도 된다 — 모드 구분은 나중에 얹을 수 있게 열어 둔 것이다.
MOTOR_DEFAULT_MODE = 2

# 안전 타임아웃(초). START 후 이 시간이 지나면 정지 조건과 무관하게 멈춘다.
#
# 왜 필요한가: 정지 조건은 "확정 보행자가 있었다가 사라짐"이다. 모형이 탈선하거나
# 검출이 계속 실패하면 그 조건이 **영영 오지 않고 모터가 계속 돈다.** 물리 장치라
# 조용한 실패가 아니라 실제 손상으로 이어진다.
#
# 30cm를 2.5cm/s로 12초에 통과하고, 기본 녹색 10초 + 최대 연장 10초 = 20초이므로
# 그보다 넉넉히 잡는다. 정상 동작 중에는 절대 발동하지 않아야 하는 값이다.
MOTOR_MAX_RUN_SEC = 40.0


# =====================================================================
# 쓰러짐 연출용 서보모터 — src/servo.py  (시연 전용)
# =====================================================================
# 모형 사람을 실제로 눕혀서 쓰러짐 감지를 시연한다. 손으로 넘어뜨리면 프레임 안에
# 사람 손이 들어와 검출을 교란하므로, 원격으로 눕히는 편이 낫다.
#
# 이건 **감지 대상을 만드는 장치**이지 감지 결과에 반응하는 장치가 아니다.
# 그래서 파이프라인이 아니라 main.py가 타이머로 직접 돌린다.

# BCM 번호. 하드웨어 PWM 채널(PWM0)이라 지터가 적다.
# GPIO 12/13은 이미 L298N의 ENA/ENB가 쓰고 있어 피했다.
SERVO_PIN = 18

# 서 있는 각도 / 쓰러진 각도.
# 서보 혼(horn)을 어느 방향으로 끼웠느냐에 따라 부호가 달라지므로 실물 보고 맞출 것.
SERVO_STAND_ANGLE_DEG = 0
SERVO_FALL_ANGLE_DEG = 80

# SG90 계열 호환 펄스폭(초). gpiozero 기본값(1.0ms/2.0ms)은 SG90에서 가동범위가
# 90도 정도로 좁게 나온다. 0.5~2.5ms로 넓혀야 180도가 나온다.
SERVO_MIN_PULSE_WIDTH_SEC = 0.0005
SERVO_MAX_PULSE_WIDTH_SEC = 0.0025

# --fall-after 를 생략했을 때 쓸 기본 지연(초). 카메라 앞에 모형을 놓을 시간.
SERVO_FALL_AFTER_SEC = 5.0

# 눕힌 뒤 다시 세우기까지의 시간(초). --fall-hold 로 덮어쓸 수 있다.
#
# 왜 '계속 누워 있음'이 기본이 아닌가: 데모에서는 쓰러졌다가 **다시 일어나 마저 건너는**
# 것까지 보여야 한다. 부저가 켜지는 것만큼 꺼지는 것도 확인 대상이다.
#
# 5초 근거: FALL_CONFIG["fall_clear_sec"] = 3.0 이므로 일으켜 세운 뒤 3초가 지나야
# 알람이 풀린다. 눕힌 채로 최소 그만큼은 둬야 "쓰러짐 확정 -> 부저"가 관찰되고,
# 일으킨 뒤에도 3초를 더 봐야 "해제 -> 부저 꺼짐"이 보인다.
SERVO_FALL_HOLD_SEC = 5.0
