# =====================================================================
# 위치 기반(구역별) 신호 연장 
# =====================================================================
# 횡단보도를 "걷는 방향"을 따라 위치 순서대로 5개 구역으로 나눈다.
#
#   진입 끝 ┃ 1 │ 2 │ 3 │ 4 │ 5 ┃ 반대 끝
#           └───┴───┴───┴───┴───┘
#   1, 5 = 양 끝(시작) 구역   2, 4 = 끝과 중앙 사이 구역   3 = 정중앙 구역
#
# 남은 신호 시간이 임계값 이하일 때, 보행자가 "어느 구역에 있는지"에 따라 연장 시간을 차등한다.
# (가운데에 있을수록 아직 더 건너야 하므로 더 길게 연장.)
CROSSWALK_ZONE_COUNT = 5

# =====================================================================
# 아래 값들은 **아두이노(제어부)가 쓰는 값**이다. 파이 코드는 읽지 않는다.
# =====================================================================
# 파이는 "가장 덜 건넌 사람이 몇 번째 구역인가"(ZONE <1..N>)만 보내고, 얼마나 연장할지는
# 제어부가 정한다. 잔여 녹색 시간을 7세그먼트로 직접 세는 쪽만 "지금 뒤처졌는가"에 답할 수 있기 때문이다.
# 기본 보행 녹색 시간(초). 아래 기준표의 기준이 된다.
BASE_GREEN_SEC = 10

# 구역별 '정상 도착 기준 잔여시간' — 아두이노가 이 표와 실제 잔여시간을 비교한다.
#
#     기준[n] = BASE_GREEN_SEC x (1 - (2n-1)/(2N))
#     10초 / 5구역 -> {1: 9, 2: 7, 3: 5, 4: 3, 5: 1}
#
# 뜻: "정상 보행 속도로 걸었다면 n번째 구역 중점에 도착했을 때 이만큼 남아 있어야 한다."
# 실제 잔여시간이 이보다 적으면 그 사람은 뒤처진 것이고, 그만큼 조금씩 연장한다.
# 이 표가 정상 보행 속도를 암묵적으로 담고 있다. 그래서 파이가 속도를 재서 넘길
# 필요가 없고, 느린 사람(교통약자 포함)은 기준 대비 지연이 크게 잡혀 자동으로 더
# 연장받는다 — 별도의 교통약자 검출이 필요 없는 이유다.
ZONE_ARRIVAL_BASE_SEC = {
    n: BASE_GREEN_SEC * (1 - (2 * n - 1) / (2 * CROSSWALK_ZONE_COUNT))
    for n in range(1, CROSSWALK_ZONE_COUNT + 1)
}

# 1회 연장량(초). 여러 번 나눠 주기 위한 값이다.
# 크게 한 번 주는 대신 조금씩 여러 번 주는 이유: 보행자가 곧바로 횡단을 마치면 이미 붙은
# 연장은 되돌릴 수 없다. 낭비의 상한이 곧 이 값이므로 작을수록 차량 대기가 줄어든다.
# 그리고 매 구역에서 지연을 다시 재는 피드백 루프가 되어, 사람이 나가면 즉시 멈춘다.
# 2초 근거: 파이의 상태 재전송 주기(SERIAL_STATE_HEARTBEAT_SEC = 1초)보다 커야 한다.
# 1초로 하면 하트비트마다 연장이 붙어 7세그먼트가 계속 깜빡이는 것처럼 보인다.
MAX_SINGLE_EXTEND_SEC = 2

# 연장 누적 상한(초). 차량 신호와의 충돌 방지를 위한 안전 상한.
# 근거: 강진군 보행신호 자동연장 시스템이 "허용된 시간(5~10초) 범위 내에서" 연장한다는
# 운영 사례의 상한값 (docs/decisions.md 참고).
#
# ⚠️ 아두이노 구현 시 주의: 파이는 조건이 유지되는 동안 같은 ZONE을 계속 재전송한다
# (유실 복구용). 받을 때마다 더하면 녹색이 무한히 늘어난다 — team_interface.md 참고.
MAX_TOTAL_EXTENSION_SEC = 10

# 검출 흔들림에 대비해, 횡단보도(아무 구역) 안에서 이만큼 연속 검출돼야 "확정 보행자"로 본다.
ZONE_RESIDENCY_FRAMES = 2    # TODO(실측 필요): 실측 FPS 기반으로 튜닝.

