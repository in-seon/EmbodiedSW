#
# 왜 '초'가 아니라 '프레임 수'인가: 잔류 확정(ZONE_RESIDENCY_FRAMES) 자체가 프레임 수 기준이라
# 유예도 같은 단위여야 섞이지 않는다. FALL_CONFIG의 track_grace_sec이 '초 + 프레임 배수' 적응형인
