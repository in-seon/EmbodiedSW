from pathlib import Path

_PROJECT_ROOT = Path(__file__).resolve().parents[1]
_WEIGHT_DIRS = (_PROJECT_ROOT, _PROJECT_ROOT.parent)

def _weight_path(name: str) -> str:

    for directory in _WEIGHT_DIRS:
        path = directory / name
        if path.exists():
            return str(path)
    return name

