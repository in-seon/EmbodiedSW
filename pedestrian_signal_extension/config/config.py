# 프로젝트 루트를 기준으로 절대 경로를 만든다. 상대 경로("data/zone_config.json")로 두면
# **어느 디렉터리에서 실행하느냐에 따라 파일을 못 찾는다.
# 주의: 조각에 앞 슬래시를 붙이지 말 것("/data" X, "data" O).
