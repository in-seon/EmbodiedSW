#     부족분 = 예상 통과 시간(ETA) x ETA_SAFETY_MARGIN - 남은 신호 시간
#     연장   = min( ZONE_EXTENSION_SEC[구역], ceil(부족분) )      # 부족분 <= 0 이면 연장 안 함
