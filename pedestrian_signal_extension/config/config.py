# --- 축척과 '모형 보행자 속도' — 연장 시간이 그대로 유효한 이유 ---
#
# 위 치수는 실제 4차선 횡단보도(폭 400cm x 길이 1200cm)의 **1:40 축소판**이다.
# 폭(400->10)과 길이(1200->30)의 축척비가 같아 왜곡 없이 대응된다.
#
# 중요한 것은 거리 축척이 아니라 **시간 축척**이다. 연장 시간은 거리가 아니라 시간이고,
#
#     시간 축척 = 거리 축척 / 속도 축척
#
# 이므로, 모형 보행자를 **실제 보행속도의 1/40 = 2.5 cm/s** 로 움직이면 시간 축척이 1:1이
# 되어 ZONE_EXTENSION_SEC / MAX_TOTAL_EXTENSION_SEC 의 국내 운영 사례 값을 그대로 쓸 수 있다.
#
#     검산: 30cm / 2.5cm/s = 12초  ==  실제 12m / 1.0m/s = 12초  (일치)
#
# 따라서 **모터 속도를 2.5 cm/s에 맞추는 것이 연장 초를 바꾸는 것보다 낫다.**
# 값을 임의로 축소하면 근거 자료(광주시 5초, 서울시 3~6초, 강진군 5~10초)와의 연결이
# 끊어진다. src/motor.py의 STEP_DELAY로 조정하고, 실제로 30cm 이동에 12초가 걸리는지
# 스톱워치로 확인할 것.
#
# 모터가 그보다 빨라서 2.5cm/s를 못 맞추면 그때는 시간 축척만큼 연장 초를 나눈다
# (예: 5cm/s -> 통과 6초 -> 시간 축척 1:2 -> 3번 구역 5초 대신 3초).
# 그 경우에도 비율 3 : 5 : 상한 10 은 유지할 것 — docs/decisions.md 참고.

